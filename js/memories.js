const memoryList = document.getElementById("memory-list");
const gallery = document.getElementById("memory-gallery");
const pathSvg = document.getElementById("memory-path");
const pathLine = document.getElementById("memory-path-line");
const pathHearts = document.getElementById("memory-path-hearts");

/* Reveal photos as they enter the screen */

let memoryObserver = null;

if ("IntersectionObserver" in window) {
    memoryObserver = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add("visible");
                memoryObserver.unobserve(entry.target);
            }
        });
    }, {
        threshold: 0.05
    });
}

/* Render photo cards */

function renderMemories() {
    if (!memoryList || !gallery) {
        console.error("Memories gallery elements were not found.");
        return;
    }

    memoryList.replaceChildren();

    memoryPhotos.forEach((memory, index) => {
        const item = document.createElement("article");
        item.className = "memory-item";

        const frame = document.createElement("div");
        frame.className = "memory-frame";

        const image = document.createElement("img");
        image.src = memory.image;
        image.alt = memory.alt || `Memory ${index + 1}`;
        image.loading = index < 2 ? "eager" : "lazy";
        image.decoding = "async";

        image.addEventListener("load", () => {
            requestAnimationFrame(drawMemoryPath);
        });

        image.addEventListener("error", () => {
            image.remove();
            frame.classList.add("memory-image-error");

            const message = document.createElement("span");
            message.className = "memory-error-message";
            message.textContent =
                "Photo not found. Check the file name and path.";

            frame.appendChild(message);
            requestAnimationFrame(drawMemoryPath);
        }, { once: true });

        frame.appendChild(image);
        item.appendChild(frame);
        memoryList.appendChild(item);

        if (memoryObserver) {
            memoryObserver.observe(item);
        } else {
            item.classList.add("visible");
        }
    });

    requestAnimationFrame(drawMemoryPath);
}

/* Draw the continuous heart-shaped path */

function drawMemoryPath() {
    if (!gallery || !memoryList || !pathSvg || !pathLine) return;

    const items = [...memoryList.querySelectorAll(".memory-item")];

    if (!items.length) {
        pathSvg.style.display = "none";
        return;
    }

    const galleryRect = gallery.getBoundingClientRect();
    const width = gallery.clientWidth;
    const height = gallery.scrollHeight;

    if (width <= 0 || height <= 0) return;

    pathSvg.style.display = "block";
    pathSvg.style.width = `${width}px`;
    pathSvg.style.height = `${height}px`;
    pathSvg.setAttribute("viewBox", `0 0 ${width} ${height}`);

    // Connect each photo at the edge facing the next photo.
    const points = items.map((item, index) => {
        const frame = item.querySelector(".memory-frame");
        const rect = frame.getBoundingClientRect();

        return {
            x: index % 2 === 0
                ? rect.right - galleryRect.left
                : rect.left - galleryRect.left,
            y: rect.top - galleryRect.top + rect.height / 2
        };
    });

    let path = `M ${points[0].x} ${points[0].y}`;

    for (let i = 1; i < points.length; i++) {
        const start = points[i - 1];
        const end = points[i];

        const dx = end.x - start.x;
        const dy = end.y - start.y;
        const distance = Math.hypot(dx, dy);

        // Smaller screens automatically use smaller heart curves.
        const repeats = Math.max(2, Math.floor(distance / 55));
        const stepX = dx / repeats;
        const stepY = dy / repeats;

        for (let j = 0; j < repeats; j++) {
            const x1 = start.x + stepX * j;
            const y1 = start.y + stepY * j;
            const x2 = start.x + stepX * (j + 1);
            const y2 = start.y + stepY * (j + 1);

            const midX = (x1 + x2) / 2;
            const midY = (y1 + y2) / 2;

            const halfWidth = Math.min(
                24,
                Math.max(12, Math.abs(stepX) * 0.35)
            );

            const halfHeight = Math.min(
                25,
                Math.max(14, Math.abs(stepY) * 0.2 + 14)
            );

            const direction = j % 2 === 0 ? -1 : 1;

            // Approach the heart's centre indentation.
            path +=
                ` C ${x1 + stepX * 0.25} ${y1},` +
                ` ${midX - halfWidth} ${midY - halfHeight * direction},` +
                ` ${midX} ${midY}`;

            // Draw the first rounded lobe and pointed bottom.
            path +=
                ` C ${midX - halfWidth * 1.5} ${midY - halfHeight * direction},` +
                ` ${midX - halfWidth * 1.25} ${midY + halfHeight * direction},` +
                ` ${midX} ${midY + halfHeight * 0.65}`;

            // Draw the second rounded lobe.
            path +=
                ` C ${midX + halfWidth * 1.25} ${midY + halfHeight * direction},` +
                ` ${midX + halfWidth * 1.5} ${midY - halfHeight * direction},` +
                ` ${midX} ${midY}`;

            // Continue toward the next connecting point.
            path +=
                ` C ${midX + halfWidth} ${midY - halfHeight * direction},` +
                ` ${x2 - stepX * 0.25} ${y2},` +
                ` ${x2} ${y2}`;
        }
    }

    pathLine.setAttribute("d", path);

    // Remove any previously drawn separate heart symbols.
    if (pathHearts) {
        pathHearts.setAttribute("d", "");
    }
}

/* Initialize */

renderMemories();

window.addEventListener("load", () => {
    requestAnimationFrame(drawMemoryPath);
});

window.addEventListener("resize", () => {
    requestAnimationFrame(drawMemoryPath);
});

/* Keep the path aligned when the gallery changes size */

if ("ResizeObserver" in window && gallery) {
    const galleryObserver = new ResizeObserver(() => {
        requestAnimationFrame(drawMemoryPath);
    });

    galleryObserver.observe(gallery);
}
